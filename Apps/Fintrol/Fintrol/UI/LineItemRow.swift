import SwiftUI
import AppleAppLabUI
#if os(iOS)
import UIKit
#elseif os(macOS)
import AppKit
#endif

/// Custom row — not in AppleAppLabUI's catalog. Documented in PROJECT_LEARNINGS.md as a
/// "list row with per-currency caption + inline edit" generalization candidate.
struct LineItemRow: View {
    @Bindable var line: LineItem
    let exchangeRate: Decimal?
    let isEditing: Bool
    /// True while this row is a freshly-created draft from "Agregar ingreso/gasto" that
    /// hasn't been confirmed yet — gates the empty-line validation and shows "Cancelar".
    let isDraft: Bool
    let onStartEditing: () -> Void
    let onCommit: () -> Void
    let onDelete: (() -> Void)?
    /// Only used while `isDraft` — discards the draft line entirely (Bertrand's ghost-row fix).
    let onDiscardDraft: (() -> Void)?
    /// User's change (replaces the old per-row "Pagado" toggle): swipe-leading toggles
    /// `isActive` and must run `recomputeForward` (it affects every total), so the parent
    /// owns persistence + recompute exactly like `onCommit` does for an inline edit.
    let onToggleActive: () -> Void
    /// Swipe-trailing's first action: toggles `isPaid`, a purely visual flag — no recompute.
    let onTogglePaid: () -> Void

    @State private var amountText: String = ""
    @Environment(\.accessibilityReduceMotion) private var reduceMotion

    /// A draft with an empty description or a non-positive amount must not be saveable —
    /// this is exactly the ghost-line bug Bertrand reproduced.
    private var isValidForSave: Bool {
        PeriodCoordinator.isValidManualLine(title: line.title, amount: line.amount)
    }

    /// Three distinct origin icons per Jonny (DESIGN_LIQUID.md): recurring, subscription and
    /// service are visually distinguishable at a glance, all overridden to `pencil` once the
    /// user has manually edited that line ("this came from X but has its own value here").
    private var isAutoGeneratedOrigin: Bool {
        line.origin == .recurring || line.origin == .subscription || line.origin == .loan || line.origin == .investment
    }

    /// Coordinator (2026-09-15): the row no longer shows an origin icon at all (description,
    /// amount, and the "pagado" checkmark only) — but per Sarah's rule that an icon must
    /// never be the *only* indicator of origin, that information stays available: it's folded
    /// into `accessibilityStateValue` below (VoiceOver) and still shown as plain text in the
    /// edit sheet's context (the row's own origin never needed a visual cue for sighted users
    /// beyond the description itself once the icon is gone).
    private var originLabel: String? {
        if line.isManuallyEdited, isAutoGeneratedOrigin {
            return "editado manualmente"
        }
        switch line.origin {
        case .manual: return nil
        case .recurring: return "recurrente"
        case .subscription: return line.isHomeService ? "servicio del hogar" : "suscripción"
        case .loan: return "préstamo"
        case .investment: return "inversión"
        case .carryOver: return "arrastrado del mes anterior"
        }
    }

    private var isTitleEditable: Bool {
        line.origin != .carryOver
    }

    private var carryOverEditHint: String? {
        line.origin == .carryOver ? "No se puede editar porque es arrastrado del mes anterior" : nil
    }

    private var convertedCaption: String? {
        guard line.currency == .mxn, let exchangeRate, exchangeRate > 0 else { return nil }
        let usd = CurrencyConversion.toUSD(amount: line.amount, currency: .mxn, rate: exchangeRate)
        return "≈ \(usd.currencyString()) USD · TC \(exchangeRate.twoDecimalString)"
    }

    var body: some View {
        Group {
            if isEditing {
                editingRow
            } else {
                displayRow
            }
        }
        .padding(.vertical, 6)
    }

    /// FALLBACK from the approved plan: a `List` (the only way to get native
    /// `.swipeActions`) blocked touches to `captureRow` below it even at zero rows, confirmed
    /// in the simulator — so this row implements leading/trailing swipe itself via
    /// `DragGesture`, full-swipe-only (no partial reveal-then-tap state). Eliminar/Editar
    /// (DESIGN_LIQUID.md's 2nd trailing action, explicitly never full-swipe) stay reachable
    /// via `.contextMenu` and `accessibilityActions` instead — both already gesture-free.
    @State private var dragTranslation: CGFloat = 0
    @GestureState private var isDragging = false
    private let swipeCommitThreshold: CGFloat = 88
    /// HIG #5 (Larry): swipe-trailing's semantics stay exactly as the user decided — first
    /// action is "Marcar pagado" — but Eliminar/Editar (DESIGN_LIQUID.md's original second
    /// trailing action) needed a visible, discoverable path beyond only `.contextMenu`.
    /// Dragging trailing past this second, further threshold reveals it as a genuine second
    /// stage of the same gesture (red for Eliminar, per Larry) instead of changing what the
    /// first threshold already means.
    private let swipeSecondActionThreshold: CGFloat = 176

    private var isPastSecondTrailingThreshold: Bool { dragTranslation <= -swipeSecondActionThreshold }

    #if os(iOS)
    private func hapticImpact() {
        guard !reduceMotion else { return }
        UIImpactFeedbackGenerator(style: .light).impactOccurred()
    }
    #endif

    private var swipeGesture: some Gesture {
        DragGesture(minimumDistance: 16)
            .updating($isDragging) { _, state, _ in state = true }
            .onChanged { value in
                // Vertical drags (scrolling) must not fight this gesture.
                guard abs(value.translation.width) > abs(value.translation.height) else { return }
                dragTranslation = value.translation.width
            }
            .onEnded { value in
                let translation = value.translation.width
                let settle = { withAnimation(reduceMotion ? nil : .easeOut(duration: 0.2)) { dragTranslation = 0 } }
                if translation >= swipeCommitThreshold {
                    settle()
                    onToggleActive()
                    #if os(iOS)
                    hapticImpact()
                    #endif
                } else if translation <= -swipeSecondActionThreshold {
                    settle()
                    if line.origin == .manual, let onDelete {
                        onDelete()
                    } else {
                        onStartEditing()
                    }
                    #if os(iOS)
                    hapticImpact()
                    #endif
                } else if translation <= -swipeCommitThreshold {
                    settle()
                    onTogglePaid()
                    #if os(iOS)
                    hapticImpact()
                    #endif
                } else {
                    settle()
                }
            }
    }

    private var displayRow: some View {
        ZStack {
            // Background hint revealed under the row while dragging — matches the icons/tints
            // `.swipeActions` would have shown (DESIGN_LIQUID.md colors: never green/red,
            // those are reserved for the sobrante semaphore).
            HStack {
                Label(
                    line.isActive ? "Desactivar" : "Activar",
                    systemImage: line.isActive ? "minus.circle.fill" : "arrow.uturn.backward.circle.fill"
                )
                .labelStyle(.iconOnly)
                .foregroundStyle(line.isActive ? .gray : .blue)
                .opacity(dragTranslation > 8 ? 1 : 0)
                Spacer()
                if isPastSecondTrailingThreshold {
                    // Second stage of the same trailing gesture, per Larry's ruling: Eliminar
                    // (manual lines) or Editar (generated lines) — visible + red, never only
                    // reachable via contextMenu.
                    Label(
                        line.origin == .manual ? "Eliminar" : "Editar",
                        systemImage: line.origin == .manual ? "trash.fill" : "pencil"
                    )
                    .labelStyle(.iconOnly)
                    .foregroundStyle(line.origin == .manual ? .red : .blue)
                } else {
                    Label(
                        line.isPaid ? "Desmarcar pagado" : "Marcar pagado",
                        systemImage: line.isPaid ? "checkmark.circle.fill" : "circle"
                    )
                    .labelStyle(.iconOnly)
                    .foregroundStyle(.blue)
                    .opacity(dragTranslation < -8 ? 1 : 0)
                }
            }
            .padding(.horizontal, 12)

            rowContent
                // Coordinator (2026-09-15): a flat `Color("AppBackground")` here fought the
                // card's own `.ultraThinMaterial.opacity(0.5)` (`PeriodView.lineBlock`) —
                // in dark mode it rendered as a visibly lighter gray box per row instead of
                // blending into the card. Same Frost fill as the card, so the row still
                // occludes the swipe-hint strip behind it at rest without a mismatched tint.
                .background(.ultraThinMaterial.opacity(0.5))
                .offset(x: dragTranslation)
        }
        .clipped()
        .gesture(swipeGesture)
        .accessibilityElement(children: .combine)
        .accessibilityValue(accessibilityStateValue)
        .accessibilityActions {
            Button("Editar") { onStartEditing() }
            Button(line.isActive ? "Desactivar" : "Activar") { onToggleActive() }
            Button(line.isPaid ? "Desmarcar pagado" : "Marcar pagado") { onTogglePaid() }
            if line.origin == .manual, let onDelete {
                Button("Eliminar", role: .destructive) { onDelete() }
            }
        }
        .contextMenu {
            Button(line.isActive ? "Desactivar" : "Activar", systemImage: line.isActive ? "minus.circle.fill" : "arrow.uturn.backward.circle.fill", action: onToggleActive)
            Button(line.isPaid ? "Desmarcar pagado" : "Marcar pagado", systemImage: line.isPaid ? "checkmark.circle.fill" : "circle", action: onTogglePaid)
            Button(line.currency == .usd ? "Cambiar a MXN" : "Cambiar a USD") {
                let newCurrency: Currency = line.currency == .usd ? .mxn : .usd
                line.currency = newCurrency
                line.isManuallyEdited = line.origin != .manual ? true : line.isManuallyEdited
                onCommit()
                #if os(iOS)
                UIAccessibility.post(notification: .announcement, argument: "Moneda cambiada a \(newCurrency == .usd ? "USD" : "MXN")")
                #endif
            }
            Button("Editar", systemImage: "pencil", action: onStartEditing)
            if line.origin == .manual, let onDelete {
                Button("Eliminar", systemImage: "trash", role: .destructive, action: onDelete)
                    #if os(macOS)
                    .keyboardShortcut(.delete, modifiers: [.command, .shift])
                    #endif
            }
        }
    }

    private var rowContent: some View {
        HStack(spacing: 10) {
            VStack(alignment: .leading, spacing: 2) {
                Text(line.title)
                    .font(.body)
                if let convertedCaption {
                    Text(convertedCaption)
                        .font(.caption)
                        .foregroundStyle(.secondary)
                        .monospacedDigit()
                }
            }

            Spacer()

            Text(line.amount.currencyString(currency: line.currency))
                .font(.body.weight(.semibold))
                .monospacedDigit()
                .strikethrough(!line.isActive)

            // DESIGN_LIQUID.md: "palomita discreta (checkmark.circle.fill, 14pt, tinte .blue)
            // a la derecha del monto — no afecta números, no cambia opacidad de nada más en
            // la fila" (its own opacity still follows the row when isActive == false, per the
            // "inactiva y pagada" combined state — it's not drawn separately at full opacity).
            if line.isPaid {
                Image(systemName: "checkmark.circle.fill")
                    .font(.system(size: 14))
                    .foregroundStyle(.blue)
                    .accessibilityHidden(true)
            }
        }
        .opacity(line.isActive ? 1 : 0.4)
        .animation(reduceMotion ? nil : .easeOut(duration: 0.2), value: line.isActive)
        .contentShape(Rectangle())
        .onTapGesture {
            // While a swipe is mid-drag/revealed, a tap should dismiss it, not open edit.
            guard dragTranslation == 0 else { return }
            onStartEditing()
        }
    }

    /// DESIGN_LIQUID.md: "inactiva" / "pagada" / "inactiva, pagada" / nothing — always in this
    /// order, never conveyed by color/icon alone. `originLabel` now leads the value (the row
    /// dropped its origin icon per the coordinator, so this is the only place that
    /// information still reaches VoiceOver).
    private var accessibilityStateValue: String {
        var parts: [String] = []
        if let originLabel { parts.append(originLabel) }
        if !line.isActive { parts.append("inactiva") }
        if line.isPaid { parts.append("pagada") }
        return parts.joined(separator: ", ")
    }

    private var editingRow: some View {
        VStack(alignment: .leading, spacing: 8) {
            HStack(spacing: 8) {
                if isTitleEditable {
                    TextField("Descripción", text: $line.title)
                        .textFieldStyle(.roundedBorder)
                } else {
                    Text(line.title)
                        .foregroundStyle(.secondary)
                }
            }
            HStack(spacing: 8) {
                // Starts blank (placeholder "0.00") instead of pre-filled with "0" — a
                // pre-filled numeric TextField concatenates on the first keystroke instead
                // of replacing (typing "5" after "0.00" produced "0.005000").
                TextField("0.00", text: $amountText)
                    #if os(iOS)
                    .keyboardType(.decimalPad)
                    #endif
                    .textFieldStyle(.roundedBorder)
                    .disabled(line.origin == .carryOver)
                    .accessibilityHint(carryOverEditHint ?? "")
                    .onAppear {
                        amountText = line.amount == 0 ? "" : line.amount.twoDecimalString
                    }
                    .onChange(of: amountText) { _, newValue in
                        line.amount = Decimal(string: newValue, locale: Locale(identifier: "en_US_POSIX")) ?? 0
                    }

                Picker("Moneda", selection: $line.currency) {
                    Text("USD").tag(Currency.usd)
                    Text("MXN").tag(Currency.mxn)
                }
                .pickerStyle(.segmented)
                .frame(width: 140)
                .disabled(line.origin == .carryOver)
                .accessibilityHint(line.origin == .carryOver ? "No se puede cambiar porque es arrastrado del mes anterior" : "")

                if isDraft {
                    Button("Cancelar") {
                        onDiscardDraft?()
                    }
                    .buttonStyle(.bordered)
                }

                Button("Listo") {
                    if isDraft {
                        guard isValidForSave else { return }
                        onCommit()
                    } else {
                        if line.origin != .manual { line.isManuallyEdited = true }
                        onCommit()
                    }
                }
                .buttonStyle(.borderedProminent)
                .disabled(isDraft && !isValidForSave)
            }
            if isDraft && !isValidForSave {
                Text("Escribe una descripción y un monto mayor a 0.")
                    .font(.caption)
                    .foregroundStyle(.secondary)
            }
        }
        .padding(10)
        .background(
            RoundedRectangle(cornerRadius: 12, style: .continuous)
                .fill(Color("AppBackgroundSecondary"))
        )
    }
}
